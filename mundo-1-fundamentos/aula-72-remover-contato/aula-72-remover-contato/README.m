# Aula 72 - Removendo um contato

   Aprendi a remover um item específico de uma lista de dicionários.

   - Busco o contato pelo nome, igual na Aula 71.
   - `.remove(item)` tira esse item da lista.
   - `return` sozinho para a função ali, sem continuar checando o resto da lista.

   ## Como rodar
   No terminal, dentro desta pasta: `python main.py`
